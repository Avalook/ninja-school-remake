"""Game-ready classmate sprite sheets by HEAD SWAP onto the approved hero cutout rig.

Classmates in the original are a different head (cp/f<n>h0) on the hero's own body (cb/cl parts),
so the HD version re-uses the hero rig (art/hero/parts + scripts/blender_hero_rig.py poses) and
only replaces the head with the head of the classmate's HD master (Codex art/generated/codex_hd,
read-only; local mflux master as fallback):

  1. neck row of the master = narrowest silhouette row in 22..48 % of its height;
     head = master pixels above neck row (+ small overlap), scaled by hero body length / master body
     length (neck->sole) so the master's head:body ratio is kept, neck centre placed on the hero
     neck pivot.  head / head_hurt / head_dig parts are all replaced (no special expressions).
  2. Blender renders (patched copy of scripts/blender_hero_rig.py written to
     tools/art/cast_blender_rig.py: parts/out dirs as args + extra poses):
        idle  B0, B1 (original idle pair, B1 = breathe-in)
        talk  T0, T1 (front arm gesture, small head nods)        - new poses
        walk  W0..W5 (hero run cycle B2..B6 at 55 % amplitude + 1 in-between) - new poses
  3. Assembly exactly like scripts/hero_assemble.py (2x downsample, 1 px ink outline, sole row on
     the anchor) -> art/cast/sheets/<id>.png + .json, copied to remake/art/cast/sheets/.

    python3 tools/art/cast_rig.py [--ids stu5_sakura,stu7_toniku]
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts"))
import cast_lib as L  # noqa: E402
import hero_assemble as HA  # noqa: E402  (read-only reuse of downsample / outline)

HERO_PARTS = L.ROOT / "art/hero/parts"
BLENDER = "/Applications/Blender.app/Contents/MacOS/Blender"
RIG_SRC = L.ROOT / "scripts/blender_hero_rig.py"
RIG_COPY = Path(__file__).resolve().parent / "cast_blender_rig.py"
CODEX = L.ROOT / "art/generated/codex_hd"
STUDENTS = ["stu0_beanie", "stu1_bald", "stu2_redspike", "stu3_dreads", "stu4_glasses",
            "stu5_sakura", "stu6_bucket", "stu7_toniku"]
CLIPS = {"idle": [0, 1], "talk": [46, 47], "walk": [48, 49, 50, 51, 52, 53]}
EXTRA_POSES = '''
# ---- extra poses for the HD cast (tools/art/cast_rig.py) ----
POSES[46] = dict(fu=58, ff=72, bu=-4, head=3, breathe=1.01, place=("ground", 0))
POSES[47] = dict(fu=74, ff=96, bu=-6, head=-2, breathe=1.025, place=("ground", 0))
def _walk(key, k=0.55):
    return {a: v * (k if a != "torso" else 0.35) for a, v in RUN[key].items()}
for _i, _key in enumerate(("r2", "r3", "r4", "r5", "r6")):
    POSES[48 + _i] = merge(_walk(_key), dict(place=("ground", 0)))
POSES[53] = merge({a: 0.5 * (_walk("r6")[a] + _walk("r2")[a]) for a in RUN["r2"]}, dict(place=("ground", 0)))
'''


def write_rig_copy():
    s = RIG_SRC.read_text()
    s = s.replace('ap.add_argument("--no-render", action="store_true")',
                  'ap.add_argument("--no-render", action="store_true")\n'
                  '    ap.add_argument("--parts-dir", required=True)\n'
                  '    ap.add_argument("--out-dir", required=True)')
    s = s.replace('parts_dir = root / "art/hero/parts"', 'parts_dir = Path(args.parts_dir)')
    s = s.replace('raw = root / "art/hero/build/raw"', 'raw = Path(args.out_dir) / "raw"')
    s = s.replace('(root / "art/hero/build/render-report.json")', '(Path(args.out_dir) / "render-report.json")')
    s = s.replace('blend = root / "art/blender/hero_rig.blend"', 'blend = Path(args.out_dir) / "rig.blend"')
    s = s.replace('blend=str(blend.relative_to(root))', 'blend=str(blend)')
    s = s.replace("for b in range(46):", "for b in sorted(POSES):")
    s = s.replace("scene.frame_start, scene.frame_end = 0, 45", "scene.frame_start, scene.frame_end = 0, max(POSES)")
    s = s.replace("scene.frame_end = 100 + len(tweens) if tweens else 45",
                  "scene.frame_end = 100 + len(tweens) if tweens else max(POSES)")
    s = s.replace("or list(range(46))", "or sorted(POSES)")
    # tweens start at frame 100: keep extra poses below that
    marker = "ANGLE_BONE = {"
    s = s.replace(marker, EXTRA_POSES + "\n" + marker, 1)
    s = '"""GENERATED by tools/art/cast_rig.py from scripts/blender_hero_rig.py - do not edit."""\n' + s
    RIG_COPY.write_text(s)


def master_for(cid):
    p = CODEX / f"{cid}.png"
    if p.is_file():
        return p
    p = L.CAST / f"{cid}.png"
    return p if p.is_file() else None


def neck_row(op):
    ys = np.nonzero(op.any(1))[0]
    y0, y1 = ys.min(), ys.max()
    widths = op.sum(1)
    lo, hi = int(y0 + 0.22 * (y1 - y0)), int(y0 + 0.48 * (y1 - y0))
    # smooth widths a little so a single thin row of hair does not win
    w = np.convolve(widths, np.ones(5) / 5, mode="same")
    r = lo + int(np.argmin(w[lo:hi]))
    return r, y0, y1


def build_parts(cid, outdir):
    src = master_for(cid)
    m = np.array(Image.open(src).convert("RGBA"))
    op = m[..., 3] >= 128
    neck, y0, y1 = neck_row(op)
    meta = json.loads((HERO_PARTS / "parts.json").read_text())
    pv = meta["pivots"]
    hero_body = pv["ground"][1] - pv["neck"][1]
    k = hero_body / float(y1 + 1 - neck)
    overlap = int(0.025 * (y1 - y0))
    head = m[: neck + overlap].copy()
    xs = np.nonzero(op[neck])[0]
    ncx = (xs.min() + xs.max()) / 2.0
    hi = Image.fromarray(head)
    hi = hi.resize((max(1, round(hi.width * k)), max(1, round(hi.height * k))), Image.LANCZOS)
    canvas = Image.new("RGBA", tuple(meta["source_size"]), (0, 0, 0, 0))
    ox = int(round(pv["neck"][0] - ncx * k))
    oy = int(round(pv["neck"][1] - neck * k))
    canvas.alpha_composite(hi, (max(0, ox), max(0, oy)) if ox >= 0 and oy >= 0 else (0, 0))
    if ox < 0 or oy < 0:
        canvas = Image.new("RGBA", tuple(meta["source_size"]), (0, 0, 0, 0))
        canvas.paste(hi, (ox, oy), hi)
    bb = canvas.getbbox()
    part = canvas.crop(bb)
    pdir = outdir / "parts"
    if pdir.exists():
        shutil.rmtree(pdir)
    shutil.copytree(HERO_PARTS, pdir, ignore=shutil.ignore_patterns("debug_*"))
    for name in ("head", "head_hurt", "head_dig"):
        part.save(pdir / f"{name}.png")
        meta["parts"][name] = {"file": f"{name}.png", "offset": [bb[0], bb[1]], "size": list(part.size)}
    meta["source"] = f"head swap: {src.relative_to(L.ROOT)} on {meta['source']}"
    (pdir / "parts.json").write_text(json.dumps(meta, indent=1))
    return {"master": str(src.relative_to(L.ROOT)), "neck_row": int(neck), "scale": round(k, 4),
            "head_offset": [bb[0], bb[1]], "head_size": list(part.size)}


def render(outdir):
    frames = sorted(sum(CLIPS.values(), []))
    cmd = [BLENDER, "--background", "--factory-startup", "--python-exit-code", "1",
           "--python", str(RIG_COPY), "--", "--project-root", str(L.ROOT),
           "--parts-dir", str(outdir / "parts"), "--out-dir", str(outdir),
           "--frames", ",".join(map(str, frames))]
    t0 = time.time()
    p = subprocess.run(cmd, capture_output=True, text=True, timeout=900)
    (outdir / "blender.log").write_text(p.stdout[-6000:] + "\n" + p.stderr[-6000:])
    if p.returncode != 0:
        raise RuntimeError("blender failed: " + p.stderr[-1500:])
    return round(time.time() - t0, 1)


def assemble(cid, outdir):
    rep = json.loads((outdir / "render-report.json").read_text())
    scale = int(rep["render_scale"])
    m = int(rep.get("margin", 0))
    cell = HA.CELL
    order = [b for clip in ("idle", "talk", "walk") for b in CLIPS[clip]]
    cells = []
    for b in order:
        canvas = HA.add_outline(HA.downsample(Image.open(outdir / "raw" / f"b{b:02d}.png"), scale))
        al = canvas[..., 3]
        ys, xs = np.nonzero(al >= 0.5)
        shift = HA.ANCHOR[1] - (ys.max() - m)
        y0 = m - shift
        cells.append(HA.to_image(canvas[y0:y0 + cell, m:m + cell]))
    sheet = Image.new("RGBA", (cell * len(cells), cell), (0, 0, 0, 0))
    for i, c in enumerate(cells):
        sheet.alpha_composite(c, (i * cell, 0))
    sd = L.CAST / "sheets"
    sd.mkdir(parents=True, exist_ok=True)
    sheet.save(sd / f"{cid}.png", optimize=True)
    frames, i = {}, 0
    for clip in ("idle", "talk", "walk"):
        frames[clip] = list(range(i, i + len(CLIPS[clip])))
        i += len(CLIPS[clip])
    meta = {"cell": [cell, cell], "anchor": list(HA.ANCHOR), "cols": len(cells), "count": len(cells),
            "frames": frames, "fps": {"idle": 2, "talk": 4, "walk": 10}, "facing": "right",
            # same density as the hero sheet: 201 sheet px = 42 world px (hero original 36 px)
            "scale": round(42.0 / 201.0, 5), "rig_pose_ids": order,
            "source": "hero cutout rig + head of " + json.loads(
                (outdir / "parts/parts.json").read_text())["source"]}
    (sd / f"{cid}.json").write_text(json.dumps(meta, indent=1))
    rd = L.ROOT / "remake/art/cast/sheets"
    rd.mkdir(parents=True, exist_ok=True)
    shutil.copy(sd / f"{cid}.png", rd / f"{cid}.png")
    shutil.copy(sd / f"{cid}.json", rd / f"{cid}.json")
    return meta


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ids", default="")
    a = ap.parse_args()
    write_rig_copy()
    ids = [i for i in a.ids.split(",") if i] or STUDENTS
    rep = {}
    for cid in ids:
        out = L.CAST / "rig" / cid
        out.mkdir(parents=True, exist_ok=True)
        info = build_parts(cid, out)
        info["blender_seconds"] = render(out)
        info["sheet"] = assemble(cid, out)["frames"]
        rep[cid] = info
        print(cid, info["blender_seconds"], "s", flush=True)
    p = L.CAST / "rig_report.json"
    old = json.loads(p.read_text()) if p.is_file() else {}
    old.update(rep)
    p.write_text(json.dumps(old, indent=1))


if __name__ == "__main__":
    main()
